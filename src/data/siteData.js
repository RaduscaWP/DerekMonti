function countArticleWords(article) {
  const sectionWords = article.sections.flatMap((section) => [
    section.heading,
    ...(section.paragraphs || []),
    ...(section.bullets || []),
  ]);
  return [article.title, article.excerpt, ...sectionWords]
    .join(' ')
    .trim()
    .split(/\s+/)
    .filter(Boolean).length;
}

